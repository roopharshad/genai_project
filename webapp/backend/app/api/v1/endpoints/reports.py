router = APIRouter()

@router.get("/")
def list_reports(
    project_id: Optional[str] = Query(None),
    user: User = Depends(get_current_user),
    db: Session = Depends(get_db)
):
    """List reports strictly filtered by accessible projects."""
    accessible_p_ids = get_accessible_project_ids(db, user)
    if not accessible_p_ids:
        return []

    query = db.query(Report)
    if project_id:
        verify_project_access(db, user, project_id)
        query = query.filter(Report.project_id == project_id)
    else:
        query = query.filter(Report.project_id.in_(accessible_p_ids))

    return query.order_by(Report.created_at.desc()).all()


@router.get("/export/csv")
def export_metrics_csv(
    project_id: Optional[str] = Query(None),
    user: User = Depends(get_current_user),
    db: Session = Depends(get_db)
):
    """Export quality evaluation metrics as CSV for authorized projects."""
    accessible_p_ids = get_accessible_project_ids(db, user)
    if not accessible_p_ids:
        evals = []
    else:
        query = db.query(EvaluationResult).join(RestorationJob, EvaluationResult.job_id == RestorationJob.id)
        if project_id:
            verify_project_access(db, user, project_id)
            query = query.filter(RestorationJob.project_id == project_id)
        else:
            query = query.filter(RestorationJob.project_id.in_(accessible_p_ids))
        evals = query.all()

    output = io.StringIO()
    writer = csv.writer(output)
    writer.writerow([
        "Evaluation ID", "Job ID", "Has Reference", "PSNR (dB)", "SSIM", 
        "LPIPS", "OCR Word Accuracy", "OCR Char Accuracy", "Edge Preservation Score", 
        "Inference Time (ms)", "Created At"
    ])

    for e in evals:
        writer.writerow([
            e.id, e.job_id, e.has_reference,
            e.psnr if e.psnr is not None else "N/A",
            e.ssim if e.ssim is not None else "N/A",
            e.lpips if e.lpips is not None else "N/A",
            e.ocr_word_acc if e.ocr_word_acc is not None else "N/A",
            e.ocr_char_acc if e.ocr_char_acc is not None else "N/A",
            e.edge_preservation_score if e.edge_preservation_score is not None else "N/A",
            e.inference_time_ms if e.inference_time_ms is not None else "N/A",
            e.created_at.isoformat()
        ])

    output.seek(0)
    return Response(
        content=output.getvalue(),
        media_type="text/csv",
        headers={"Content-Disposition": "attachment; filename=docrestore_evaluation_metrics.csv"}
    )


def _fmt(v, nd=3):
    return "—" if v is None else (f"{v:.{nd}f}" if isinstance(v, float) else str(v))


def _write_pdf(path, project, user, title, evals, db):
    """Real PDF (reportlab) with a summary and one row per evaluated restoration."""
    from datetime import datetime
    from reportlab.lib import colors
    from reportlab.lib.pagesizes import A4, landscape
    from reportlab.lib.styles import getSampleStyleSheet
    from reportlab.lib.units import mm
    from reportlab.platypus import Paragraph, SimpleDocTemplate, Spacer, Table, TableStyle

    styles = getSampleStyleSheet()
    doc = SimpleDocTemplate(str(path), pagesize=landscape(A4), leftMargin=14 * mm, rightMargin=14 * mm,
                            topMargin=14 * mm, bottomMargin=14 * mm, title=title, author="DocRestore AI")
    story = [Paragraph(title, styles["Title"]),
             Paragraph(f"Project: {project.name} &nbsp;·&nbsp; Generated by {user.full_name} "
                       f"&nbsp;·&nbsp; {datetime.now().strftime('%Y-%m-%d %H:%M')}", styles["Normal"]),
             Spacer(1, 6 * mm)]

    def avg(xs):
        xs = [x for x in xs if x is not None]
        return round(sum(xs) / len(xs), 4) if xs else None

    dq = [((e.metrics_detail or {}).get("document_quality") or {}) for e in evals]
    summary = [["Restorations evaluated", str(len(evals))],
               ["Average quality score (0-100)", _fmt(avg([d.get("quality_score") for d in dq]), 1)],
               ["Average damage reduction", _fmt(avg([d.get("damage_reduction_pct") for d in dq]), 1) + " %"],
               ["Average stroke preservation", _fmt(avg([d.get("stroke_preservation") for d in dq]), 4)],
               ["Average PSNR vs original (dB)", _fmt(avg([e.psnr for e in evals]), 2)],
               ["Average SSIM vs original", _fmt(avg([e.ssim for e in evals]), 4)],
               ["Average OCR character agreement", _fmt(avg([e.ocr_char_acc for e in evals]), 4)]]
    t = Table(summary, colWidths=[80 * mm, 50 * mm])
    t.setStyle(TableStyle([("GRID", (0, 0), (-1, -1), 0.4, colors.grey),
                           ("BACKGROUND", (0, 0), (0, -1), colors.HexColor("#F1ECFA")),
                           ("FONTSIZE", (0, 0), (-1, -1), 9)]))
    story += [Paragraph("Summary", styles["Heading2"]), t, Spacer(1, 6 * mm),
              Paragraph("Per-restoration results", styles["Heading2"])]

    from app.models.entities import Asset
    rows = [["Document", "Date", "Quality", "Damage before→after", "Strokes kept", "PSNR", "SSIM", "OCR agree", "Time (s)"]]
    for e, d in zip(evals, dq):
        job = db.query(RestorationJob).filter(RestorationJob.id == e.job_id).first()
        asset = db.query(Asset).filter(Asset.id == job.asset_id).first() if job else None
        name = (asset.original_filename if asset else "—")[:40]
        rows.append([name, e.created_at.strftime("%Y-%m-%d %H:%M"), _fmt(d.get("quality_score"), 1),
                     f"{_fmt(d.get('damage_score_before'), 1)} → {_fmt(d.get('damage_score_after'), 1)}",
                     _fmt(d.get("stroke_preservation"), 4), _fmt(e.psnr, 2), _fmt(e.ssim, 4), _fmt(e.ocr_char_acc, 4),
                     _fmt(e.inference_time_ms / 1000 if e.inference_time_ms else None, 1)])
    if len(rows) == 1:
        rows.append(["No restorations evaluated yet"] + [""] * 8)
    t = Table(rows, repeatRows=1)
    t.setStyle(TableStyle([("GRID", (0, 0), (-1, -1), 0.3, colors.grey),
                           ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#5B2BBF")),
                           ("TEXTCOLOR", (0, 0), (-1, 0), colors.white),
                           ("FONTSIZE", (0, 0), (-1, -1), 8),
                           ("ROWBACKGROUNDS", (0, 1), (-1, -1), [colors.white, colors.HexColor("#F7F5FB")])]))
    story += [t, Spacer(1, 5 * mm),
              Paragraph("PSNR and SSIM compare each result with the uploaded original (no clean reference exists), "
                        "so they measure fidelity, not perfection. Quality score = 40% damage reduction + 30% ink "
                        "preservation + 30% text accuracy/agreement.", styles["Italic"])]
    doc.build(story)


@router.post("/generate")
def generate_pdf_report(
    project_id: str = Query(...),
    title: Optional[str] = Query(None),
    user: User = Depends(get_current_user),
    db: Session = Depends(get_db)
):
    """Generate and store a PDF restoration quality report."""
    project = verify_project_access(db, user, project_id, require_write=True)

    report_title = title or f"DocRestore AI Quality Evaluation Report — {project.name}"
    report_filename = f"report_{uuid.uuid4().hex[:12]}.pdf"
    report_path = settings.REPORTS_DIR / report_filename

    evals = (db.query(EvaluationResult).join(RestorationJob, EvaluationResult.job_id == RestorationJob.id)
             .filter(RestorationJob.project_id == project.id).order_by(EvaluationResult.created_at.desc()).all())
    psnrs = [e.psnr for e in evals if e.psnr is not None]
    ssims = [e.ssim for e in evals if e.ssim is not None]
    avg_psnr = round(sum(psnrs) / len(psnrs), 2) if psnrs else None
    avg_ssim = round(sum(ssims) / len(ssims), 4) if ssims else None
    _write_pdf(report_path, project, user, report_title, evals, db)

    rep = Report(
        project_id=project.id,
        title=report_title,
        report_type="quality_evaluation",
        stored_filename=report_filename,
        metrics_summary={"avg_psnr": avg_psnr, "avg_ssim": avg_ssim, "total_evals": len(evals), "format": "pdf"},
        created_by=user.id
    )
    db.add(rep)
    db.commit()
    db.refresh(rep)

    return {
        "status": "success",
        "id": rep.id,
        "report_id": rep.id,
        "title": rep.title,
        "stored_filename": report_filename,
        "download_url": f"/storage/reports/{report_filename}",
        "metrics_summary": rep.metrics_summary
    }


@router.get("/{report_id}/download")
def download_report(report_id: str, user: User = Depends(get_current_user), db: Session = Depends(get_db)):
    """Download a stored report (authorised by its project)."""
    from fastapi.responses import FileResponse
    rep = db.query(Report).filter(Report.id == report_id).first()
    if not rep:
        raise HTTPException(status_code=404, detail="Report not found")
    verify_project_access(db, user, rep.project_id)
    path = settings.REPORTS_DIR / rep.stored_filename
    if not path.is_file():
        raise HTTPException(status_code=404, detail="Report file is missing")
    media = "application/pdf" if path.suffix == ".pdf" else "text/plain"
    safe = "".join(ch if ch.isalnum() or ch in " -_" else "_" for ch in rep.title)[:80].strip() or "report"
    return FileResponse(path, media_type=media, filename=f"{safe}{path.suffix}")
